package ai.wolf.autopilot;

import android.text.Html;
import android.net.Uri;

import java.io.ByteArrayOutputStream;
import java.io.InputStream;
import java.net.HttpURLConnection;
import java.net.URL;
import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import javax.net.ssl.HttpsURLConnection;

/**
 * Explicitly approved, read-only search using a public search provider.
 *
 * Internet research is NOT performed for ordinary private chat questions.
 * Provider HTML can change or show a challenge; failure is disclosed, never
 * fabricated. The user can still use WOLF's interactive web browser.
 * No tokens, account cookies, phone files, learned facts or chat history are
 * transmitted. The query text alone is sent to the search service.
 */
public final class WebSearchService {
    private static final int MAX_HTML = 240_000;
    private static final Pattern LINK = Pattern.compile(
            "(?is)<a\\b([^>]{0,1200})>(.*?)</a>");
    private static final Pattern ATTR = Pattern.compile(
            "(?is)\\b%s\\s*=\\s*[\"']([^\"']{1,1200})[\"']");
    private static final Pattern SNIPPET = Pattern.compile(
            "(?is)<(?:a|div)\\b[^>]*\\bclass\\s*=\\s*[\"'][^\"']*\\bresult__snippet\\b[^\"']*[\"'][^>]*>(.*?)</(?:a|div)>");
    public static final class Result {
        public final String title, url, snippet;
        Result(String title, String url, String snippet) {
            this.title = title; this.url = url; this.snippet = snippet;
        }
    }
    public static final class Search {
        public final String query, source, searchUrl;
        public final List<Result> results;
        Search(String query, String source, String searchUrl, List<Result> results) {
            this.query = query; this.source = source;
            this.searchUrl = searchUrl; this.results = results;
        }
        /** Verified source list generated by Java, never composed by a model. */
        public String links() {
            StringBuilder out = new StringBuilder("🔗 Реальные ссылки поиска:\n");
            for (int i = 0; i < results.size(); i++)
                out.append(i + 1).append(". ").append(results.get(i).title)
                        .append("\n").append(results.get(i).url).append("\n");
            return out.toString();
        }
        /** Only small snippets reach local Qwen; never untrusted web commands. */
        public String evidence() {
            StringBuilder result = new StringBuilder();
            for (int i = 0; i < results.size(); i++) {
                Result r = results.get(i);
                result.append("ИСТОЧНИК ").append(i + 1).append(":\n")
                        .append("Заголовок: ").append(r.title).append("\n")
                        .append("Фрагмент: ").append(r.snippet).append("\n");
            }
            return result.toString().substring(0,
                    Math.min(1550, result.length()));
        }
    }
    private WebSearchService() {}

    private static String attribute(String attributes, String key) {
        Pattern p = Pattern.compile(String.format(Locale.ROOT, ATTR.pattern(), key));
        Matcher m = p.matcher(attributes);
        return m.find() ? m.group(1) : "";
    }

    private static String plain(String html) {
        if (html == null) return "";
        String result = Html.fromHtml(html, Html.FROM_HTML_MODE_LEGACY)
                .toString().replaceAll("[\\s\\u00a0]+", " ").trim();
        return result.substring(0, Math.min(result.length(), 320));
    }

    private static String publicUrl(String raw) {
        if (raw == null || raw.length() > 1300) return "";
        String candidate = raw.replace("&amp;", "&").trim();
        // DDG HTML redirects can be /l/?uddg=https%3A... .
        // Extract the actual external target and never show a tracking URL.
        int param = candidate.indexOf("uddg=");
        if (param >= 0) {
            String encoded = candidate.substring(param + 5).split("&", 2)[0];
            try { candidate = java.net.URLDecoder.decode(encoded, "UTF-8"); }
            catch (Exception ignored) { return ""; }
        }
        try {
            Uri uri = Uri.parse(candidate);
            if (!"https".equalsIgnoreCase(uri.getScheme()) ||
                    uri.getHost() == null || uri.getUserInfo() != null ||
                    uri.getPort() != -1 ||
                    candidate.contains("\n") || candidate.contains("\r")) return "";
            return candidate;
        } catch (Exception ignored) {
            return "";
        }
    }

    /**
     * Pure parser can be exercised without internet through Android tests.
     * The HTML provider may return no results (including anti-bot pages).
     */
    public static List<Result> parseHtml(String html) {
        if (html == null || html.length() > MAX_HTML + 4000)
            throw new IllegalArgumentException("Недопустимая страница результатов.");
        ArrayList<Result> entries = new ArrayList<>();
        ArrayList<String> snippets = new ArrayList<>();
        Matcher sn = SNIPPET.matcher(html);
        while (sn.find() && snippets.size() < 6)
            snippets.add(plain(sn.group(1)));
        Set<String> seen = new HashSet<>();
        Matcher links = LINK.matcher(html);
        while (links.find() && entries.size() < 5) {
            String attributes = links.group(1);
            if (!attribute(attributes, "class").contains("result__a")) continue;
            String title = plain(links.group(2));
            String url = publicUrl(attribute(attributes, "href"));
            if (title.isEmpty() || url.isEmpty() || !seen.add(url)) continue;
            String snippet = snippets.size() > entries.size() ?
                    snippets.get(entries.size()) : "Фрагмент не предоставлен поисковиком.";
            entries.add(new Result(title.substring(0, Math.min(title.length(), 105)),
                    url, snippet.substring(0, Math.min(snippet.length(), 300))));
        }
        return entries;
    }

    public static Search search(String question) throws Exception {
        if (question == null || question.trim().length() < 2 ||
                question.length() > 200)
            throw new IllegalArgumentException("Для интернет-поиска нужно 2–200 символов.");
        String query = question.trim();
        // Query itself is sent to provider only after a distinct consent
        // dialog in HomeActivity, and is never appended to other context.
        String url = "https://html.duckduckgo.com/html/?q=" +
                URLEncoder.encode(query, "UTF-8");
        HttpsURLConnection connection =
                (HttpsURLConnection) new URL(url).openConnection();
        try {
            connection.setRequestMethod("GET");
            connection.setConnectTimeout(10_000);
            connection.setReadTimeout(14_000);
            connection.setInstanceFollowRedirects(false);
            connection.setRequestProperty("User-Agent", "Mozilla/5.0 (Linux; Android 14) WOLF-AI/10.1");
            connection.setRequestProperty("Accept", "text/html");
            int status = connection.getResponseCode();
            if (status != 200) throw new IllegalStateException(
                    "Поисковик ответил HTTP " + status +
                    ". Открой поиск во встроенном браузере.");
            String type = connection.getContentType();
            if (type == null || !type.toLowerCase(Locale.ROOT).contains("text/html"))
                throw new IllegalStateException(
                        "Поисковик не вернул HTML-результаты.");
            ByteArrayOutputStream out = new ByteArrayOutputStream();
            try (InputStream input = connection.getInputStream()) {
                byte[] block = new byte[8192];
                int n;
                while ((n = input.read(block)) != -1) {
                    if (out.size() + n > MAX_HTML)
                        throw new IllegalStateException(
                                "Страница поиска больше разрешённого объёма.");
                    out.write(block, 0, n);
                }
            }
            List<Result> found = parseHtml(out.toString(StandardCharsets.UTF_8.name()));
            if (found.isEmpty()) throw new IllegalStateException(
                    "Поисковик не предоставил проверяемые результаты (возможно, защита от ботов). " +
                    "Попробуй встроенный браузер.");
            return new Search(query, "DuckDuckGo HTML", url, found);
        } finally {
            connection.disconnect();
        }
    }
}
